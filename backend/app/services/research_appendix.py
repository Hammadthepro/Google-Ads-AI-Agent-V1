"""Research & Evidence Appendix of a campaign plan version.

Built ONLY from persisted records: the task's stored audits (website, competitors, GBP/geo), the stored keyword research, the stored
feasibility estimate and the recorded research events of the run (what was fetched, searched, cached or unavailable). It is captured
when a plan version is created (CampaignPlan.evidence) so a version always shows what it was built from; edited and restored versions
carry their source's evidence. Nothing here is generated by an AI, and a metric a provider did not return is shown as unavailable.
"""
from __future__ import annotations

from collections import Counter
from urllib.parse import urlparse

from sqlalchemy.orm import Session

from app.core import clock
from app.models import Business, Task
from app.services import research_events

VERSION = 2  # 2: source ledger, keyword classification and measurement coverage, competitor verification, campaign settings
KP_PERIOD = "average monthly searches, last 12 months (Google Keyword Planner estimate)"


def _host(u: str | None) -> str:
    try:
        return (urlparse(u if "//" in (u or "") else f"https://{u}").hostname or "").removeprefix("www.")
    except ValueError:
        return ""


INFLUENCE = {
    "website": "Services, landing pages and claims used for the ad groups and ads",
    "competitors": "Competitor services and offers considered for positioning; never copied as claims",
    "keywords": "Keyword candidates and their measured metrics",
    "geo": "Service area and local competitor density",
    "gbp": "Business profile facts (location, categories)",
}


def _sources(events: list[dict]) -> tuple[list[dict], list[dict]]:
    out, unavailable, seen = [], [], set()

    def add(key, **row):
        if key in seen:
            return
        seen.add(key)
        out.append(row)
    for e in events:
        d, k, st = e.get("data") or {}, e["kind"], e.get("stage") or ""
        if k == "page_extracted":
            add(("page", d.get("url")), provider="Website crawler", url=d.get("url"), title=d.get("page_title") or e["title"], retrieved_at=e["at"],
                cached=False, extracted=", ".join(x for x in [f"{d.get('words')} words" if d.get("words") else "", f"H1 “{d['h1']}”" if d.get("h1") else ""] if x)
                or "page text", verification="retrieved", influence=INFLUENCE.get(st, "Research context"), stage=st)
        elif k == "web_result":
            add(("web", d.get("url")), provider="Tavily web search", url=d.get("url"), title=e["title"], retrieved_at=e["at"], cached=False,
                extracted="search result snippet", verification="search result (page not opened)", influence=INFLUENCE.get(st, "Research context"), stage=st)
        elif k == "serp_query":
            add(("serp", d.get("engine"), d.get("query"), d.get("location")), provider="Google results (SerpApi)", url=None,
                title=f"{(d.get('engine') or 'google').replace('_', ' ')}: “{d.get('query')}”" + (f" · {d['location']}" if d.get("location") else ""),
                retrieved_at=e["at"], cached=bool(d.get("served_from_cache")), extracted="organic results, public ads, related searches",
                verification="cached result" if d.get("served_from_cache") else "retrieved", influence=INFLUENCE.get(st, "Research context"), stage=st)
        elif k == "sponsored_ad":
            add(("ad", d.get("url")), provider="Google results (SerpApi)", url=d.get("url"), title=e["title"], retrieved_at=e["at"], cached=False,
                extracted=f"public ad copy seen for “{d.get('query')}”", verification="observed in search results (no performance data)",
                influence="Competitor messaging context", stage=st)
        elif k == "keyword_discovery":
            add(("kw", d.get("provider"), d.get("seed") or e["title"]), provider=d.get("provider") or "keyword source", url=None,
                title=f"Seed “{d.get('seed') or e['title']}”", retrieved_at=e["at"], cached=False,
                extracted=f"{d.get('count', 0)} keyword idea(s)" + (f", e.g. {', '.join((d.get('examples') or [])[:3])}" if d.get("examples") else ""),
                verification="retrieved", influence=INFLUENCE["keywords"], stage=st)
        elif k in ("provider_unavailable", "provider_failed", "page_failed", "crawl_blocked"):
            unavailable.append({"what": e["title"], "provider": d.get("provider") or "", "url": d.get("url"), "at": e["at"], "kind": k,
                                "reason": d.get("reason") or d.get("error") or (f"HTTP {d['status']}" if d.get("status") else "")})
    return out, unavailable


SOURCE_STATUSES = ("Verified", "Relevant", "Extracted", "Crawled", "Discovered", "Rejected", "Failed")


def source_ledger(events: list[dict], services: list[str], own_domain: str = "") -> dict:
    """One deduplicated record per source the research touched (search results, pages, Google results pages, ads), with how it was
    found, what was retrieved and extracted, whether it is relevant and why, and why it failed or was rejected. Statuses never claim
    more than the events show: a search result nobody opened stays `Discovered`."""
    from app.core.util import normalize_term
    from app.services.competitor_verify import excluded_reason
    svc = [(s, normalize_term(s)) for s in services if s]
    recs: dict[tuple, dict] = {}

    def get(key, **base):
        r = recs.get(key)
        if r is None:
            r = recs[key] = {"url": None, "domain": None, "title": None, "source_type": None, "discovery_method": None, "provider": None,
                             "http_status": None, "crawled_at": None, "extraction_status": "not extracted", "evidence": None,
                             "relevance_score": None, "relevance_reason": None, "verification_status": "Discovered", "failure_reason": None,
                             "stage": None, **base}
        return r

    def relevance(text: str) -> tuple[int, str]:
        t = normalize_term(text or "")
        full = [s for s, n in svc if n and n in t]
        if full:
            return 100, f"names the service “{full[0]}”"
        part = [s for s, n in svc if n and any(len(w) > 3 and w in t.split() for w in n.split())]
        if part:
            return 50, f"partly matches the service “{part[0]}”"
        return 0, "does not mention any client service"

    for e in events:
        d, k, st = e.get("data") or {}, e["kind"], e.get("stage") or ""
        url = d.get("url")
        if k == "web_result":
            r = get(("url", url), url=url, domain=_host(url), title=e["title"], source_type="web search result",
                    discovery_method="web search", provider=d.get("provider") or "web search", stage=st)
            r["evidence"] = r["evidence"] or "search result title and snippet"
            why = excluded_reason(_host(url))
            if why:
                r.update(verification_status="Rejected", failure_reason=why)
        elif k == "page_extracted":
            r = get(("url", url), url=url, domain=_host(url), source_type="web page", discovery_method="crawl" if not st else f"{st} research",
                    provider="Website crawler", stage=st)
            text = " ".join([d.get("page_title") or "", d.get("h1") or "", *(d.get("headings") or [])])
            score, why = relevance(text)
            r.update(title=d.get("page_title") or e["title"], http_status=r["http_status"] or 200, crawled_at=e["at"],
                     extraction_status=f"extracted ({d.get('words') or 0} words)" if d.get("words") else "extracted (no text)",
                     evidence=(f"H1 “{d['h1']}”" if d.get("h1") else None) or (d.get("page_title") or None),
                     relevance_score=score, relevance_reason=why, failure_reason=None)
            own = own_domain and _host(url) == own_domain
            if r["verification_status"] != "Rejected":
                r["verification_status"] = ("Verified" if score >= 50 and (own or st in ("website", "competitors")) else
                                            "Relevant" if score >= 50 else "Extracted" if d.get("words") else "Crawled")
        elif k in ("page_failed", "crawl_blocked"):
            r = get(("url", url), url=url, domain=_host(url), title=url, source_type="web page", discovery_method="crawl", provider="Website crawler",
                    stage=st)
            if r["extraction_status"].startswith("extracted"):
                continue  # a later retry of the same page succeeded
            r.update(http_status=d.get("status"), crawled_at=e["at"], verification_status="Failed",
                     failure_reason=d.get("reason") or d.get("error") or (f"HTTP {d['status']}" if d.get("status") else "could not be fetched"))
        elif k == "serp_query":
            key = ("serp", d.get("engine"), d.get("query"), d.get("location"))
            r = get(key, title=f"{(d.get('engine') or 'google').replace('_', ' ')}: “{d.get('query')}”" + (f" · {d['location']}" if d.get("location") else ""),
                    source_type="Google results page", discovery_method="search query", provider="SerpApi", stage=st)
            score, why = relevance(d.get("query") or "")
            r.update(crawled_at=e["at"], extraction_status="extracted (results, ads, related searches)", http_status=200,
                     evidence="cached result" if d.get("served_from_cache") else "retrieved live", relevance_score=score, relevance_reason=why,
                     verification_status="Verified" if score >= 50 else "Extracted")
        elif k == "sponsored_ad":
            r = get(("ad", url, d.get("query")), url=url, domain=_host(url), title=e["title"], source_type="public Google ad",
                    discovery_method=f"seen for “{d.get('query')}”", provider="SerpApi", stage=st)
            r.update(crawled_at=e["at"], extraction_status="extracted (ad copy)", evidence=d.get("description") or e["title"],
                     verification_status="Extracted")
            why = excluded_reason(_host(url))
            if why:
                r.update(verification_status="Rejected", failure_reason=why)
        elif k == "provider_failed" and d.get("provider"):
            r = get(("provider", d.get("provider"), e["title"]), title=e["title"], source_type="provider request", provider=d.get("provider"),
                    discovery_method="API request", stage=st)
            r.update(crawled_at=e["at"], verification_status="Failed", failure_reason=d.get("error_kind") or d.get("reason") or e["title"])
    out = sorted(recs.values(), key=lambda r: (SOURCE_STATUSES.index(r["verification_status"]), r["provider"] or "", r["title"] or ""))
    st = Counter(r["verification_status"] for r in out)
    crawled = sum(1 for r in out if r["crawled_at"])
    counts = {"discovered": len(out), "crawled": crawled,
              "extracted": sum(1 for r in out if r["extraction_status"].startswith("extracted")),
              "relevant": st["Relevant"] + st["Verified"], "verified": st["Verified"], "rejected": st["Rejected"], "failed": st["Failed"],
              "by_status": {s: st.get(s, 0) for s in SOURCE_STATUSES}}
    return {"records": out[:1500], "total": len(out), "counts": counts, "statuses": list(SOURCE_STATUSES),
            "policy": "Discovered = found, not opened. Crawled = fetched. Extracted = content read. Relevant = names a client service. "
                      "Verified = relevant content from the client's site, a competitor's site or a Google results page for a service. "
                      "Counts are of distinct sources."}


def _competitors(audits: dict, events: list[dict]) -> list[dict]:
    comp = (audits or {}).get("competitor") or {}
    read_hosts: dict[str, list[str]] = {}
    for e in events:
        if e["kind"] == "page_extracted" and e.get("stage") == "competitors":
            read_hosts.setdefault(_host((e.get("data") or {}).get("url")), []).append(e["data"]["url"])
    ads: dict[str, list[dict]] = {}
    for a in ((comp.get("serp") or {}).get("sponsored_ads") or []):
        if not a.get("is_client"):
            ads.setdefault(_host(a.get("link") or a.get("domain")), []).append({"title": a.get("title"), "description": a.get("description"),
                                                                                 "query": a.get("query"), "url": a.get("link")})
    rows, seen = [], set()
    for c in comp.get("competitors") or []:
        h = _host(c.get("website_url"))
        seen.add(h)
        pages = read_hosts.get(h, [])
        rows.append({"name": c["name"], "website": c.get("website_url"), "origin": "client-provided", "discovery_source": "client profile",
                     "services": c.get("services") or [], "landing_pages_reviewed": pages, "website_inspected": bool(pages),
                     "public_ads": ads.get(h, []), "findings": [*(f"Offer on site: {o.strip()}" for o in c.get("offers_on_site") or []),
                                                                *(f"Service the client does not offer: {s}" for s in c.get("services_client_lacks") or [])],
                     "keyword_ideas": c.get("keyword_ideas") or [], "evidence_urls": pages + [a["url"] for a in ads.get(h, []) if a.get("url")]})
    for c in comp.get("web_candidates") or []:
        h = _host(c.get("website_url"))
        if h in seen:
            continue
        seen.add(h)
        pages = read_hosts.get(h, [])
        rows.append({"name": c.get("name"), "website": c.get("website_url"), "origin": "discovered",
                     "discovery_source": c.get("provider") or c.get("source") or "web research", "basis": c.get("basis") or c.get("reason") or "",
                     "services": [], "landing_pages_reviewed": pages, "website_inspected": bool(pages), "public_ads": ads.get(h, []),
                     "findings": [], "keyword_ideas": [], "evidence_urls": [u for u in [c.get("website_url"), c.get("evidence_url")] if u]})
    return rows


def _metric(r: dict, name: str):
    m = (r.get("metrics") or {}).get(name) or {}
    return {"value": r.get(name), "source": m.get("source"), "basis": m.get("basis"), "note": m.get("note"), "retrieved_at": m.get("retrieved_at")}


def _keywords(kw: dict, draft: dict, location: str) -> dict:
    in_plan: dict[str, set[str]] = {}
    for g in (draft or {}).get("ad_groups") or ([draft] if (draft or {}).get("keywords") else []):
        for k in g.get("keywords", []):
            in_plan.setdefault(k["text"].lower(), set()).add(k["match_type"])
    planner = (kw or {}).get("keyword_planner") or {}
    rows = []
    table = (kw or {}).get("keywords") or []
    for r in table:
        vol = _metric(r, "avg_monthly_searches")
        measured = vol["value"] is not None
        src_labels = sorted({s.get("label") or s.get("source") for s in r.get("sources") or []})
        vsrc = str(vol.get("source") or "")
        kind = ("DataForSEO measurement (Google Ads data)" if measured and vsrc.startswith("dataforseo") else
                "Keyword Planner measurement" if measured else
                "Search suggestion" if any("suggest" in (s.get("source") or "") or "serpapi" in (s.get("source") or "") for s in r.get("sources") or []) else
                "Website / competitor term" if r.get("sources") else "AI-generated idea")
        used = sorted(in_plan.get(r["keyword"].lower(), set()))
        rows.append({"keyword": r["keyword"], "service": r.get("service"), "label": r.get("label"), "in_plan": bool(used),
                     "match_types": used or r.get("match_types") or [], "selected_by_research": bool(r.get("selected")),
                     "search_volume": vol["value"], "volume_period": KP_PERIOD if measured else None,
                     "avg_cpc": r.get("cpc"),
                     "avg_cpc_note": (f"Reported by {(_metric(r, 'cpc').get('source') or 'DataForSEO')}" if r.get("cpc") is not None else
                                      "Not returned: Keyword Planner returns top-of-page bid ranges, not average CPC; no other source reported one"),
                     "competition_index_source": "dataforseo" if r.get("competition_index") is not None else None,
                     "competition": r.get("competition"), "competition_index": r.get("competition_index"),
                     "top_of_page_bid_low": (r.get("low_top_of_page_bid_micros") or 0) / 1e6 if r.get("low_top_of_page_bid_micros") else None,
                     "top_of_page_bid_high": (r.get("high_top_of_page_bid_micros") or 0) / 1e6 if r.get("high_top_of_page_bid_micros") else None,
                     "geo": (", ".join(r["planner_location"]) if isinstance(r.get("planner_location"), list) else r.get("planner_location"))
                            or (f"{location} (business service area; no planner targeting for this row)" if location else None),
                     "language": r.get("planner_language") or None, "retrieved_at": r.get("retrieved_at"),
                     "providers": src_labels, "measurement": kind,
                     "unavailable_reason": None if measured else (vol["note"] or "No source returned search volume"),
                     "reason": (r.get("label_reason") if r.get("label") == "IRRELEVANT" else r.get("selection_basis") or "")
                               + (f"; relevance {r['relevance_score']}/100" if r.get("relevance_score") is not None else ""),
                     "uncertainty": r.get("uncertainty"), "ad_group": r.get("ad_group"),
                     "keyword_class": r.get("keyword_class"), "keyword_class_label": r.get("keyword_class_label"),
                     "class_reason": r.get("class_reason"), "intent": r.get("intent"),
                     "location_relevance": r.get("location_relevance"), "location_reason": r.get("location_reason"),
                     "commercial_relevance": r.get("commercial_relevance"),
                     "selection_status": r.get("selection_status") or ("eligible" if r.get("selected") else "research_only"),
                     "rejection_reason": r.get("rejection_reason"),
                     "measurement_status": r.get("measurement_status") or ("measured" if measured else "unmeasured"),
                     "unmeasured_reason": r.get("unmeasured_reason"), "metric_source": r.get("metric_source"),
                     "overlap": r.get("overlap") or []})
    rows.sort(key=lambda x: (not x["in_plan"], not x["selected_by_research"], -(x["search_volume"] or 0)))
    selected = [x for x in rows if x["in_plan"] or x["selected_by_research"]]
    rejected = [x for x in rows if not (x["in_plan"] or x["selected_by_research"])]
    d4s = (kw or {}).get("dataforseo") or {}
    return {"keyword_planner": {"available": bool(planner.get("available")), "reason": planner.get("reason") or "",
                                "failed_services": planner.get("failed_services") or [], "access_level": planner.get("access_level"),
                                "access_note": planner.get("access_note")},
            "dataforseo": {"used": bool(d4s.get("used")), "reason": d4s.get("reason"), "metrics": d4s.get("metrics") or {},
                           "errors": d4s.get("errors") or [], "not_measured_rejected": d4s.get("not_measured_rejected") or {}},
            "measurement_coverage": (kw or {}).get("measurement") or {}, "classes": (kw or {}).get("classes") or {},
            "overlaps": (kw or {}).get("overlaps") or [], "rows": rows[:3000],
            "selected": selected, "rejected": rejected[:80], "rejected_total": len(rejected),
            "measured": sum(1 for x in rows if x["search_volume"] is not None), "total": len(rows),
            "policy": (kw or {}).get("metrics_policy") or ""}


def _feasibility(fz: dict, competitors: list[dict], audits: dict) -> dict:
    s = (fz or {}).get("summary") or {}
    inputs = (fz or {}).get("inputs") or {}
    geo = ((audits or {}).get("gbp") or {}).get("geo") or {}
    return {"is_estimate": True, "verdict": (fz or {}).get("status"),
            "expected_weekly_leads": s.get("expected_weekly_conversions"), "realistic_weekly_range": s.get("realistic_weekly_range"),
            "estimated_cpl": s.get("expected_cost_per_lead"), "allowed_cpl": s.get("allowed_cost_per_lead"),
            "suggested_monthly_budget": s.get("recommended_monthly_budget"), "daily_budget": s.get("daily_budget"),
            "cpc_assumption": inputs.get("cpc") or inputs.get("assumed_cpc") or s.get("cpc"),
            "conversion_rate_assumption": inputs.get("conversion_rate") or inputs.get("cvr") or s.get("conversion_rate"),
            "assumption_sources": inputs.get("sources") or inputs.get("basis"),
            "competitor_density": {"client_provided": sum(1 for c in competitors if c["origin"] == "client-provided"),
                                   "discovered": sum(1 for c in competitors if c["origin"] == "discovered"),
                                   "local_businesses_found": len(geo.get("competitors") or geo.get("places") or [])},
            "geo": {k: geo.get(k) for k in ("available", "center", "radius_km", "provider", "reason") if k in geo},
            "bottlenecks": (fz or {}).get("bottlenecks") or [], "computed_at": (fz or {}).get("created_at"),
            "limitations": "Projections from the feasibility model and the measured inputs above; not a guarantee of results."}


def build(db: Session, task: Task, ctx: dict | None = None, draft: dict | None = None) -> dict:
    """The appendix for the research this task holds now (called when a plan version is created)."""
    from app.services import tasks_service
    if ctx is None or not ctx.get("keywords"):
        ctx = {**tasks_service.research_for_retry(db, task)["ctx"], **(ctx or {})}
    events = research_events.list_events(db, run_id=task.id, limit=2000)
    biz = db.get(Business, task.business_id) if task.business_id else None
    location = ", ".join(a.get("label", "") for a in (biz.service_areas or [])[:3]) if biz and biz.service_areas else (biz.address if biz else "")
    sources, unavailable = _sources(events)
    ledger = source_ledger(events, [sv.name for sv in (biz.services if biz else []) if not sv.is_excluded], _host(biz.website_url) if biz else "")
    comp_v = ((ctx.get("audits") or {}).get("competitor") or {}).get("verification") or {}
    from app.services import campaign_settings
    settings = campaign_settings.resolve(biz, task.fields or {}) if biz else None
    competitors = _competitors(ctx.get("audits") or {}, events)
    kw = _keywords(ctx.get("keywords") or {}, draft or {}, location or "")
    providers = Counter(s["provider"] for s in sources)
    serp = [s for s in sources if s["provider"] == "Google results (SerpApi)" and s["title"].count("“")]
    return {"version": VERSION, "captured_at": clock.now().isoformat(), "task_id": task.id, "sources": sources, "competitors": competitors,
            "source_ledger": ledger, "competitor_verification": comp_v, "settings": settings,
            "provider_errors": _provider_errors(unavailable),
            "keywords": kw, "feasibility": _feasibility(ctx.get("feasibility") or {}, competitors, ctx.get("audits") or {}),
            "methodology": {
                "integrations_used": [{"provider": p, "records": n} for p, n in providers.most_common()],
                "searches": [s["title"] for s in serp] + [s["title"] for s in sources if s["provider"] not in ("Website crawler", "Google results (SerpApi)", "Tavily web search")][:40],
                "cached": [s["title"] for s in sources if s["cached"]],
                "unavailable": unavailable,
                "rejected_evidence": {"keywords_rejected": kw["rejected_total"], "pages_failed_or_blocked": sum(1 for u in unavailable if u["kind"] in ("page_failed", "crawl_blocked"))},
                "derivation": ["One ad group per selected service; keywords come from the stored keyword research (exact and phrase match only).",
                               "Keywords without measured search volume were kept only on relevance and intent, and are marked as such.",
                               "Claims in ads are limited to the business's verified claims; competitor offers are context, never copied.",
                               "The budget split and bidding are decided by rules; the AI drafted structure and copy within them."],
                "events_recorded": len(events)}}


def _provider_errors(unavailable: list[dict]) -> list[dict]:
    """Failures grouped by provider: how many, the distinct reasons, first and last time."""
    g: dict[str, dict] = {}
    for u in unavailable:
        p = u.get("provider") or ("Website crawler" if u["kind"] in ("page_failed", "crawl_blocked") else "other")
        e = g.setdefault(p, {"provider": p, "count": 0, "reasons": [], "first_at": u["at"], "last_at": u["at"]})
        e["count"] += 1
        r = (u.get("reason") or u.get("what") or "")[:200]
        if r and r not in e["reasons"]:
            e["reasons"].append(r)
        e["first_at"], e["last_at"] = min(e["first_at"], u["at"]), max(e["last_at"], u["at"])
    for e in g.values():
        e["reasons"] = e["reasons"][:6]
    return sorted(g.values(), key=lambda e: -e["count"])
